const fs=require('fs');
const path=require('path');
const {pathToFileURL}=require('url');
const {chromium}=require('../../tools/rea/node_modules/playwright-core');
const root=path.resolve(__dirname,'../..');
const output=path.join(root,'reports/regional_growth_report_v1');
const qa=path.join(output,'qa');
fs.mkdirSync(qa,{recursive:true});
const report=path.join(output,'지역별_집값상승_분석보고서_v1.html');
(async()=>{
 const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1000},deviceScaleFactor:1,acceptDownloads:true,offline:true});
 const page=await context.newPage();
 const errors=[],requests=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url());});
 await page.goto(pathToFileURL(report).href,{waitUntil:'load'});
 await page.evaluate(()=>document.fonts.ready);
 const checks={};
 checks.initialLines=await page.locator('.price-line').count();
 if(checks.initialLines!==3)throw Error('Expected3 initial metro lines');
 checks.regionCards=await page.locator('.region-card').count();
 checks.returnsRows=await page.locator('#returns-table tbody tr').count();
 if(checks.regionCards!==7||checks.returnsRows!==7)throw Error('Region count');
 checks.renderedCagrValues=await page.locator('#returns-table tbody tr').evaluateAll(rows=>{
   const data=JSON.parse(document.getElementById('report-data').textContent);let count=0;
   rows.forEach((row,i)=>{
     const values=[...row.querySelectorAll('td')].slice(0,3);
     values.forEach((cell,j)=>{
       const actual=Number(cell.textContent.replace('%','').replace('−','-'));
       const expected=Number(data.summaries[data.regions[i]][`cagr_${[3,5,10][j]}y_pct`].toFixed(2));
       if(Math.abs(actual-expected)>1e-8)throw Error('Rendered CAGR mismatch');count++;
     });
   });return count;
 });
 if(checks.renderedCagrValues!==21)throw Error('Incomplete displayed CAGR check');
 await page.screenshot({path:path.join(qa,'desktop-top.png')});
 await page.locator('#paths').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(qa,'desktop-chart.png')});
 await page.getByRole('button',{name:'전체',exact:true}).click();
 checks.allLines=await page.locator('.price-line').count();
 if(checks.allLines!==7)throw Error('All-region control');
 for(const mode of ['peak','long','start']){
   await page.locator(`[data-mode="${mode}"]`).click();
   checks[`mode_${mode}`]=await page.locator('#chart-basis').innerText();
   if(await page.locator('.price-line').count()!==7)throw Error('Mode lost selected lines');
   const invalid=await page.locator('.price-line').evaluateAll(nodes=>nodes.some(n=>/NaN|undefined|Infinity/.test(n.getAttribute('d'))));
   if(invalid)throw Error('Invalid SVG geometry');
 }
 await page.locator('[data-mode="long"]').click();
 const sejongPath=await page.locator('.price-line[data-region="세종"]').getAttribute('d');
 checks.sejongLongStart=sejongPath.split(' ')[0];
 if(Number(sejongPath.match(/^M([\d.]+)/)[1])<400)throw Error('Sejong incorrectly connected before2015');
 await page.locator('#main-chart').focus();
 await page.keyboard.press('ArrowLeft');
 checks.keyboardReadout=await page.locator('#chart-readout').innerText();
 if(!checks.keyboardReadout.includes('2026년 1분기'))throw Error('Keyboard chart readout');
 await page.getByRole('button',{name:'수도권',exact:true}).click();
 await page.locator('[data-mode="start"]').click();
 for(const region of ['서울','경기','인천'])await page.locator(`#region-legend [data-region="${region}"]`).click();
 checks.emptySelection=await page.locator('#chart-readout').innerText();
 if(!checks.emptySelection.includes('하나 이상'))throw Error('Empty selection not handled');
 await page.getByRole('button',{name:'수도권',exact:true}).click();
 const downloadPromise=page.waitForEvent('download');
 await page.locator('#download-csv').click();
 const download=await downloadPromise;
 await download.saveAs(path.join(qa,'downloaded-calculations.csv'));
 const sourceCSV=fs.readFileSync(path.join(root,'analysis/housing_growth_2006/regional_expansion_v1/regional_summary.csv'),'utf8').replace(/^\uFEFF/,'').replace(/\r\n/g,'\n');
 const downloadedCSV=fs.readFileSync(path.join(qa,'downloaded-calculations.csv'),'utf8').replace(/^\uFEFF/,'').replace(/\r\n/g,'\n');
 if(sourceCSV!==downloadedCSV)throw Error('CSV content mismatch');
 checks.csvMatches=true;
 await page.evaluate(()=>{window.print=()=>{window.printCalled=true;};});
 await page.locator('#print-report').click();
 checks.printButton=await page.evaluate(()=>window.printCalled===true);
 await page.locator('#sensitivity').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(qa,'desktop-sensitivity.png')});
 checks.desktopOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:path.join(qa,'mobile-top.png')});
 await page.locator('#paths').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(qa,'mobile-chart.png')});
 checks.mobileOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);
 await page.locator('#regions').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(qa,'mobile-regions.png')});
 await page.emulateMedia({media:'print'});
 checks.printHeading=await page.title();
 await page.setViewportSize({width:1440,height:1000});
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:path.join(qa,'print-preview.png')});
 const staticContext=await browser.newContext({javaScriptEnabled:false,offline:true,viewport:{width:390,height:844}});
 const staticPage=await staticContext.newPage();
 await staticPage.goto(pathToFileURL(report).href,{waitUntil:'load'});
 checks.withoutJavaScriptCards=await staticPage.locator('.region-card').count();
 if(checks.withoutJavaScriptCards!==7)throw Error('Static fallback missing region charts');
 await staticContext.close();
 if(checks.desktopOverflow||checks.mobileOverflow)process.stdout.write(JSON.stringify(checks));
 if(checks.desktopOverflow||checks.mobileOverflow)throw Error('Page horizontal overflow');
 if(errors.length||requests.length)throw Error('JS errors or unexpected network requests');
 fs.writeFileSync(path.join(qa,'browser_checks.json'),JSON.stringify({status:'pass',offline:true,checks,jsErrors:errors,networkRequests:requests,resolutionDesktop:[1440,1000],resolutionMobile:[390,844],visualInspection:'screenshots pending agent inspection'},null,2));
 await browser.close();
 process.stdout.write(JSON.stringify({status:'pass',checks,jsErrors:errors.length,networkRequests:requests.length}));
})().catch(e=>{process.stderr.write(e.stack);process.exit(1);});
